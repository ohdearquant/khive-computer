"""`kc build`: an image with the toolchains your projects need, generated and built in one command. The
published image is the computer; this writes a Dockerfile that starts FROM it and adds the layers asked
for (a stable Rust under /opt/cargo owned by the action user, Node 22 and npm, Debian packages), then
hands that Dockerfile to `docker build` on stdin. Nobody edits a Dockerfile or passes build arguments.
Toolchains belong in the image, not in a running container: a container's writable layer is gone when
it is recreated, only the data directory persists (ADR-0006 A4)."""

from __future__ import annotations

import subprocess
from collections.abc import Sequence

DEFAULT_BASE = "ghcr.io/ohdearquant/khive-computer:latest"
_APT = "apt-get update && apt-get install -y --no-install-recommends {pkgs} && rm -rf /var/lib/apt/lists/*"


def dockerfile(*, base: str = DEFAULT_BASE, rust: bool = False, node: bool = False, apt: Sequence[str] = ()) -> str:
    """The Dockerfile `kc build` builds. Deterministic in its arguments; `kc build --print` shows it."""
    lines = [
        "# generated by `kc build`: the base image is the computer, these layers are its toolchains",
        f"FROM {base}",
        "USER root",
    ]
    if apt:
        lines.append("RUN " + _APT.format(pkgs=" ".join(sorted(set(apt)))))
    if node:
        lines.append(
            "RUN "
            + _APT.format(pkgs="curl ca-certificates gnupg").replace(" && rm -rf /var/lib/apt/lists/*", "")
            + " \\\n    && curl -fsSL https://deb.nodesource.com/setup_22.x | bash - \\\n"
            "    && apt-get install -y --no-install-recommends nodejs && rm -rf /var/lib/apt/lists/*"
        )
    if rust:
        lines += [
            "ENV RUSTUP_HOME=/opt/rustup CARGO_HOME=/opt/cargo",
            "RUN " + _APT.format(pkgs="curl ca-certificates build-essential pkg-config libssl-dev") + " \\\n"
            "    && curl -fsSL https://sh.rustup.rs | sh -s -- -y --profile minimal --default-toolchain stable --no-modify-path \\\n"
            "    && chown -R kc:kc /opt/rustup /opt/cargo",
            'ENV PATH="/opt/cargo/bin:$PATH"',
        ]
    return "\n".join(lines) + "\n"


def build(tag: str, text: str, *, docker: str = "docker") -> int:
    """`docker build -t <tag> -` with the Dockerfile on stdin: no build context, nothing on disk."""
    return subprocess.run([docker, "build", "-t", tag, "-"], input=text.encode(), check=False).returncode
